export const categories = ['All', 'Action', 'Adventure', 'Shooter', 'Puzzle', 'Racing', 'Strategy', 'RPG', 'Sports'];

export function mergeGames(...lists) {
  const seen = new Map();
  for (const list of lists) {
    for (const game of list || []) {
      if (!game?.title) continue;
      const key = String(game.id || game.title).toLowerCase();
      if (!seen.has(key)) seen.set(key, { ...game, id: key });
    }
  }
  return [...seen.values()];
}
